/* Notes de suite et relevé de données dans l'app : outils, refus, PDF téléchargeable, écran. */
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { chromium } = require('playwright-core');
const { demarrer } = require('./client.js');
const EX = path.join(__dirname, '..', '..', 'note-clinique-epfl', 'exemples');
const lire = n => fs.readFileSync(path.join(EX, n), 'utf8');
const CHROMIUM = process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
(async () => {
  const { client, fermer, port } = await demarrer();
  const ok = m => console.log('  ok  ' + m);
  const appel = (name, args) => client.callTool({ name, arguments: args });
  const fiche = JSON.parse(lire('fiche_exemple.json'));
  let r = await appel('demarrer_note_clinique', { type: 'suite' });
  assert(r.content[0].text.includes('NOTES DE SUITE')); ok('démarrer : procédure des notes de suite');
  r = await appel('demarrer_note_clinique', { type: 'releve' });
  assert(r.content[0].text.includes('RELEVÉ') && r.content[0].text.includes('etat_civil')); ok('démarrer : procédure du relevé avec le modèle des rubriques');
  r = await appel('afficher_note_de_suite', { regime: 'suite-courte', texte: lire('suite_courte_exemple.txt'), fiche });
  assert.strictEqual(r.structuredContent.vue, 'resultat'); ok('note courte conforme → affichée');
  r = await appel('afficher_note_de_suite', { regime: 'suite-courte', texte: 'Deuxième entretien. Absence d\'idées suicidaires. Travail sur la dynamique relationnelle.', fiche });
  assert.strictEqual(r.structuredContent.vue, 'refus'); ok('note courte fautive → refusée (' + r.structuredContent.blocages.length + ' erreurs)');
  r = await appel('afficher_note_de_suite', { regime: 'suite-transmission', texte: lire('suite_transmission_exemple.txt') });
  assert.strictEqual(r.structuredContent.vue, 'resultat'); ok('note de transmission conforme → affichée');
  r = await appel('controler_texte', { type: 'suite-transmission', texte: 'CADRE DE L\'ENTRETIEN\n\nTroisième entretien.' });
  assert(JSON.parse(r.content[0].text.split('\n\n')[0]).erreurs.length >= 4); ok('transmission incomplète : rubriques manquantes détectées');
  r = await appel('preparer_releve', { releve: { choix: { etat_civil: 'mariée', screening: 'non', symptomes_screening: 'oui' } } });
  assert.strictEqual(r.structuredContent.vue, 'refus'); ok('relevé incohérent → refusé');
  const rel = JSON.parse(lire('releve_exemple.json')); delete rel._lisezmoi;
  r = await appel('preparer_releve', { releve: rel });
  const s = r.structuredContent;
  assert.strictEqual(s.vue, 'releve'); assert.strictEqual(s.appliques.length, 22); ok('relevé conforme → 22 valeurs par défaut, lien ' + s.lien.replace(/[^/]+\.pdf$/, '….pdf'));
  const rep = await fetch(s.lien); const octets = Buffer.from(await rep.arrayBuffer());
  assert.strictEqual(rep.status, 200); assert(octets.subarray(0, 5).toString() === '%PDF-'); ok(`PDF téléchargeable (${Math.round(octets.length / 1024)} Ko)`);
  const sortiePdf = path.join(process.env.CAPTURES || os.tmpdir(), 'releve_app.pdf'); fs.writeFileSync(sortiePdf, octets);
  assert.strictEqual((await fetch(s.lien.replace(/[^/]+\.pdf$/, 'inconnu.pdf'))).status, 404); ok('lien inconnu → 404');
  const html = (await client.readResource({ uri: 'ui://widget/note-clinique-v2.html' })).contents[0].text;
  await fermer();
  const f = path.join(os.tmpdir(), 'ecran-releve.html'); fs.writeFileSync(f, html);
  const b = await chromium.launch({ executablePath: CHROMIUM }); const p = await b.newPage(); const err = []; p.on('pageerror', e => err.push(e.message));
  await p.addInitScript(o => { window.openai = { toolOutput: o, theme: 'light', setWidgetState() {}, openExternal: ({ href }) => { window.__ouvert = href; } }; }, s);
  await p.goto('file://' + f);
  await p.click('#pdf'); assert.strictEqual(await p.evaluate(() => window.__ouvert), s.lien); ok('écran relevé : le bouton ouvre le PDF');
  assert((await p.textContent('#racine')).includes('Situation economique')); ok('écran relevé : rubriques vides listées');
  await p.screenshot({ path: path.join(process.env.CAPTURES || os.tmpdir(), 'ecran-releve.png'), fullPage: true });
  assert(!err.length, err.join()); await b.close();
  console.log('SUITE ET RELEVÉ : tous les tests passent (PDF : ' + sortiePdf + ')');
  process.exit(0);
})().catch(e => { console.error('ÉCHEC', e); process.exit(1); });
